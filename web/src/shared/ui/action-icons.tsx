export type ActionIconName = keyof typeof icons;
export default function ActionIcon({
  name,
  className = '',
  ...props
}: { name: ActionIconName } & LucideProps) {
  const Icon = icons[name];
  return (
    <Icon
      size={20}
      strokeWidth={1.5}
      aria-hidden="true"
      focusable="false"
      {...props}
      className={`action-icon ${className}`}
      data-action-glyph={name}
    />
  );
}
