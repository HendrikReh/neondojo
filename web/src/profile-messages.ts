export type ProfileMessageKey = keyof typeof rows;
const localeIndex: Record<Locale, number> = {
  en: 0,
  de: 1,
  es: 2,
  fr: 3,
  it: 4,
  pl: 5,
};
export const profileMessageKeys = Object.keys(rows) as ProfileMessageKey[];
export function profileText(
  locale: Locale,
  key: ProfileMessageKey,
  params: Record<string, string | number> = {},
) {
  return rows[key][localeIndex[locale]].replace(
    /\{(\w+)\}/g,
    (_, name: string) => String(params[name] ?? ''),
  );
}
export function useProfileText() {
  const { locale } = useI18n();
  return (key: ProfileMessageKey, params?: Record<string, string | number>) =>
    profileText(locale, key, params);
}
export function profileFieldKey(path: string): ProfileMessageKey | undefined {
  const leaf = path.split('.').at(-1)!;
  return Object.hasOwn(rows, leaf) ? (leaf as ProfileMessageKey) : undefined;
}
