type Key = keyof typeof rows;
const locales: Locale[] = ['en', 'de', 'es', 'fr', 'pl', 'it'];
export function sourceText(
  locale: Locale,
  key: Key,
  params: TranslationParams = {},
) {
  return interpolate(rows[key][locales.indexOf(locale)], params);
}
export function useSourceText() {
  const { locale } = useI18n();
  return (key: Key, params?: TranslationParams) =>
    sourceText(locale, key, params);
}

export const openingBookProviders = [
  'automatic',
  'backgammondb',
  'xg',
  'off',
] as const;

export function openingBookProviderLabel(
  locale: Locale,
  provider: (typeof openingBookProviders)[number],
) {
  switch (provider) {
    case 'backgammondb':
      return 'BackgammonDB';
    case 'xg':
      return 'eXtreme Gammon (XG)';
    case 'automatic':
    case 'off':
      return sourceText(locale, provider);
  }
}
